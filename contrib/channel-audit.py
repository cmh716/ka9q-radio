def load_catalog():
    spec = importlib.util.spec_from_file_location(
        'frequency_catalog', Path(__file__).with_name('frequency-catalog.py'))
    catalog = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(catalog)
    return catalog


# Stable wire option numbers from src/status.h.
INPUT_SAMPLES, DATA_DEST, SSRC, SAMPLE_RATE = 13, 17, 18, 20
FREQUENCY, FIRST_LO, DEMOD, PL_TONE = 33, 34, 48, 61
FE_LOW, FE_HIGH = 100, 101
RTP_PT, ENCODING, DCS_CODE, DCS_INVERTED = 105, 107, 122, 123
RTP_PORT, STATUS_PORT = 5004, 5006
POLL = bytes((1, SSRC, 4, 255, 255, 255, 255, 0))
POLL_INTERVAL = 10
STATUS_TIMEOUT = 3 * POLL_INTERVAL
PCM_RATE = 24000
MANIFEST_FIELDS = ['ID', 'Name', 'RX MHz', 'Mode', 'Receive tone', 'Channel', 'Reason']


def multicast(value):
    address = ipaddress.IPv4Address(value)
    if not address.is_multicast:
        raise ValueError(f'{value} must be an IPv4 multicast address')
    return str(address)


def prepare(args, catalog):
    group = multicast(args.group)
    center = Decimal(catalog.mhz(args.center))
    if not math.isfinite(args.samprate) or args.samprate <= 0:
        raise ValueError('sample rate must be positive and finite')
    half_width = Decimal(str(args.samprate)) * Decimal('0.47') / 1000000 - Decimal('0.008')
    if half_width <= 0:
        raise ValueError('sample rate is too narrow for the coverage margin')
    master = catalog.indexed(catalog.read_csv(args.workspace / 'master.csv', ['ID']), 'master.csv')
    manifest, sections = [], {}
    for raw in master.values():
        row = catalog.upgrade(raw)
        profiles = row['Profiles'].replace(';', ' ').replace(',', ' ').split()
        if args.profile not in profiles and '*' not in profiles:
            continue
        rx = catalog.mhz(row['RX MHz'])
        mode = row['RX Mode'].upper()
        kind = row['RX Squelch Type'].lower()
        value = row['RX Squelch Value']
        tone, reason, channel = '', '', ''
        if mode not in ('FM', 'FMN') or kind not in ('ctcss', 'dcs'):
            reason = 'requires FM with a listed CTCSS or DCS tone'
        else:
            catalog.validate(row)
            tone = (f'{Decimal(value).normalize():f} PL' if kind == 'ctcss' else
                    ('I' if row['RX DCS Polarity'].lower() == 'inverted' else 'D') + value)
            if kind == 'ctcss' and Decimal(value) > 3000:
                reason = 'CTCSS tone exceeds radiod’s supported range'
            elif abs(Decimal(rx) - center) > half_width:
                reason = 'outside the configured audit coverage'
            else:
                preset = 'pm' if mode == 'FM' else 'npm'
                channel = f'{rx}|{tone}'
                if channel not in sections or mode == 'FM':
                    sections[channel] = (
                        f'mode = {preset}\ndata = {group}\nadvertise = no\n'
                        f'encoding = s16be\nchannels = 1\nsamprate = {PCM_RATE}\n'
                        f'freq = {int(Decimal(rx) * 1000000)}\n'
                        f'tone = {tone.split()[0] if kind == "ctcss" else 0}\n'
                        f'dcs = {tone if kind == "dcs" else "off"}\n')
        manifest.append(dict(zip(MANIFEST_FIELDS, [row['ID'], row['Name'], rx, mode, tone, channel, reason])))
    if not manifest:
        raise ValueError(f'no master entries are assigned to profile {args.profile}')
    config = '# Generated by channel-audit.py\n' + ''.join(
        f'\n[channel-audit-{number}]\n{section}' for number, section in enumerate(sections.values(), 1))
    catalog.atomic_text(args.directory / '90-channel-audit.conf', config)
    catalog.write_csv(args.directory / 'manifest.csv', MANIFEST_FIELDS, manifest)
    catalog.atomic_text(args.directory / 'group.txt', group + '\n')
    print(f'{len(manifest)} catalog entries, {len(sections)} tone-gated receiver channels')


def status_options(packet):
    if not packet or packet[0] != 0:
        return {}
    result = {}
    pos = 1
    while pos < len(packet):
        tag = packet[pos]
        pos += 1
        if tag == 0:
            return result
        if pos == len(packet):
            break
        length = packet[pos]
        pos += 1
        if length & 128:
            size = length & 127
            if not 1 <= size <= 4 or pos + size > len(packet):
                break
            length = int.from_bytes(packet[pos:pos + size], 'big')
            pos += size
        if pos + length > len(packet):
            break
        result[tag] = packet[pos:pos + length]
        pos += length
    return {}


def pcm_payload(packet):
    if len(packet) < 12 or packet[0] >> 6 != 2:
        return None
    flags, pt, seq, timestamp, ssrc = struct.unpack_from('!BBHII', packet)
    start = 12 + 4 * (flags & 15)
    end = len(packet)
    if flags & 16:
        if start + 4 > end:
            return None
        start += 4 + 4 * struct.unpack_from('!H', packet, start + 2)[0]
    if flags & 32:
        if packet[-1] == 0:
            return None
        end -= packet[-1]
    if end <= start or (end - start) % 2:
        return None
    return pt & 127, seq, timestamp, ssrc, packet[start:end]


class Audit:
    def __init__(self, manifest, group, evidence, minimum, gap):
        self.manifest = manifest
        self.destination = socket.inet_aton(group) + struct.pack('!H', RTP_PORT)
        self.evidence = evidence
        self.minimum = minimum
        self.gap = gap
        self.channels = {}
        for row in manifest:
            if not row['Channel']:
                continue
            freq, tone = row['Channel'].split('|')
            if tone.endswith(' PL'):
                tone = struct.pack('!f', float(tone[:-3]))
            self.channels[freq, tone] = row['Channel']
        self.streams = {}

    def stats(self, channel):
        return self.evidence.setdefault(channel, {'seconds': 0, 'count': 0, 'first': '', 'last': ''})

    def status(self, packet, sender, now):
        options = status_options(packet)

        def number(tag):
            return int.from_bytes(options.get(tag, b''), 'big')

        def real(tag, fmt):
            size = struct.calcsize(fmt)
            value = options.get(tag, b'')
            return struct.unpack(fmt, value.rjust(size, b'\0'))[0] if len(value) <= size else math.nan

        stream = sender, number(SSRC)
        if not stream[1]:
            return
        previous = self.streams.get(stream)
        if options.get(DATA_DEST) != self.destination or number(DEMOD) != 1 or (
                number(SAMPLE_RATE) != PCM_RATE or number(ENCODING) != 2 or
                RTP_PT not in options or INPUT_SAMPLES not in options):
            self.streams.pop(stream, None)
            return
        freq = real(FREQUENCY, '!d')
        offset = freq - real(FIRST_LO, '!d')
        if not real(FE_LOW, '!f') + 8000 <= offset <= real(FE_HIGH, '!f') - 8000:
            self.streams.pop(stream, None)
            return
        code = number(DCS_CODE)
        tone = real(PL_TONE, '!f')
        if code and not tone:
            tone_label = f'{"I" if number(DCS_INVERTED) else "D"}{code:03d}'
        elif tone > 0 and not code:
            tone_label = struct.pack('!f', tone)
        else:
            tone_label = ''
        channel = self.channels.get((f'{freq / 1e6:.6f}', tone_label))
        if not channel or any(key != stream and info['channel'] == channel
                              and now - info['progress'] <= STATUS_TIMEOUT
                              for key, info in self.streams.items()):
            self.streams.pop(stream, None)
            return
        samples, pt = number(INPUT_SAMPLES), number(RTP_PT)
        if (previous and previous['channel'] == channel and previous['pt'] == pt
                and now - previous['seen'] <= STATUS_TIMEOUT and samples >= previous['samples']):
            if samples > previous['samples']:
                self.stats(channel)['seconds'] += now - previous['seen']
                previous['progress'] = now
            previous.update(seen=now, samples=samples)
        else:
            self.streams[stream] = dict(channel=channel, pt=pt, seen=now, progress=now,
                                        samples=samples, seq=None, last=0, frames=0, counted=False)

    def audio(self, packet, sender, now, utc):
        parsed = pcm_payload(packet)
        if parsed is None:
            return
        pt, seq, timestamp, ssrc, payload = parsed
        stream = self.streams.get((sender, ssrc))
        if not stream or pt != stream['pt'] or now - stream['progress'] > STATUS_TIMEOUT:
            return
        quiet = stream['seq'] is None or now - stream['last'] >= self.gap
        if stream['seq'] is not None and not quiet:
            advance = (seq - stream['seq']) & 65535
            if advance == 0 or advance >= 32768:
                return
            quiet = (timestamp - stream['end']) & 0xffffffff >= self.gap * PCM_RATE
        frames = len(payload) // 2
        stream.update(seq=seq, end=(timestamp + frames) & 0xffffffff, last=now)
        if quiet:
            stream.update(frames=0, counted=False, started=utc)
        if any(payload):
            stream['frames'] += frames
            if stream['frames'] >= self.minimum * PCM_RATE:
                stats = self.stats(stream['channel'])
                if not stream['counted']:
                    stats['count'] += 1
                    stats['first'] = stats['first'] or stream['started']
                    stream['counted'] = True
                stats['last'] = utc

    def report(self, catalog, directory):
        rows = []
        for row in self.manifest:
            channel = row['Channel']
            stats = self.stats(channel) if channel else {'seconds': 0, 'count': 0, 'first': '', 'last': ''}
            result = 'not monitored'
            if stats['count']:
                result = 'heard with expected squelch'
            elif stats['seconds']:
                result = 'not heard'
            rows.append(dict(row, **{'Transmissions': stats['count'], 'First heard': stats['first'],
                                     'Last heard': stats['last'], 'Monitored hours': f"{stats['seconds'] / 3600:.3f}",
                                     'Result': result}))
        catalog.atomic_text(directory / 'evidence.json', json.dumps(self.evidence) + '\n')
        catalog.write_csv(directory / 'review.csv', MANIFEST_FIELDS + [
            'Transmissions', 'First heard', 'Last heard', 'Monitored hours', 'Result'], rows)


def listener(group, port, interface):
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    sock.bind((group, port))
    sock.setsockopt(socket.IPPROTO_IP, socket.IP_ADD_MEMBERSHIP,
                    socket.inet_aton(group) + socket.inet_aton(interface))
    return sock


def run(args, catalog):
    directory = args.directory
    manifest = catalog.read_csv(directory / 'manifest.csv', MANIFEST_FIELDS)
    if not manifest:
        raise ValueError('prepare an audit manifest first')
    group = multicast((directory / 'group.txt').read_text().strip())
    status_group = multicast(socket.gethostbyname(args.status))
    if status_group == group:
        raise ValueError('the audit audio and radiod status groups must differ')
    interface = str(ipaddress.IPv4Address(args.interface))
    if not (math.isfinite(args.minimum) and math.isfinite(args.gap) and args.minimum > 0 and args.gap > 0):
        raise ValueError('minimum and gap must be positive finite seconds')
    state = directory / 'evidence.json'
    evidence = json.loads(state.read_text()) if state.exists() else {}
    audit = Audit(manifest, group, evidence, args.minimum, args.gap)
    stopped = False

    def stop(*_):
        nonlocal stopped
        stopped = True

    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)
    with (listener(group, RTP_PORT, interface) as audio,
          listener(status_group, STATUS_PORT, interface) as status,
          socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sender,
          selectors.DefaultSelector() as selector):
        sender.setsockopt(socket.IPPROTO_IP, socket.IP_MULTICAST_IF, socket.inet_aton(interface))
        selector.register(status, selectors.EVENT_READ)
        selector.register(audio, selectors.EVENT_READ)
        print(f'Watching {len(audit.channels)} channels on {group}; review at {directory / "review.csv"}',
              flush=True)
        next_poll = next_report = 0
        try:
            while not stopped:
                now = time.monotonic()
                if now >= next_poll:
                    sender.sendto(POLL, (status_group, STATUS_PORT))
                    next_poll = now + POLL_INTERVAL
                    audit.streams = {key: stream for key, stream in audit.streams.items()
                                     if now - stream['seen'] <= STATUS_TIMEOUT}
                if now >= next_report:
                    audit.report(catalog, directory)
                    next_report = now + 30
                for key, _ in selector.select(0.25):
                    packet, address = key.fileobj.recvfrom(65535)
                    if args.source and address[0] != args.source:
                        continue
                    now = time.monotonic()
                    if key.fileobj is status:
                        audit.status(packet, address[0], now)
                    else:
                        audit.audio(packet, address[0], now, datetime.now(timezone.utc).isoformat(timespec='seconds'))
        finally:
            audit.report(catalog, directory)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    setup = commands.add_parser('prepare', help='generate a config fragment and catalog manifest')
    setup.add_argument('--directory', type=Path, required=True)
    setup.add_argument('--workspace', type=Path, required=True)
    setup.add_argument('--profile', default='verify-uhf')
    setup.add_argument('--group', required=True, help='unused IPv4 audio multicast address')
    setup.add_argument('--center', required=True, help='front end center in MHz')
    setup.add_argument('--samprate', type=float, required=True, help='front end sample rate in Hz')
    watch = commands.add_parser('run', help='listen and maintain review.csv')
    watch.add_argument('--directory', type=Path, required=True)
    watch.add_argument('--status', required=True, help='radiod IPv4 status multicast address or name')
    watch.add_argument('--interface', default='0.0.0.0', help='local IPv4 address of the multicast interface')
    watch.add_argument('--source', help='accept packets only from this radiod IPv4 address')
    watch.add_argument('--minimum', type=float, default=0.5, help='minimum nonzero audio seconds per transmission')
    watch.add_argument('--gap', type=float, default=0.75, help='gap in seconds that separates transmissions')
    args = parser.parse_args()
    try:
        if args.command == 'prepare':
            args.directory.mkdir(parents=True, exist_ok=True)
        with (args.directory / '.channel-audit.lock').open('a') as lock:
            try:
                fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError as exc:
                raise ValueError(f'{args.directory}: audit already in use') from exc
            (prepare if args.command == 'prepare' else run)(args, load_catalog())
    except (OSError, ValueError, csv.Error) as exc:
        parser.exit(1, f'{exc}\n')


if __name__ == '__main__':
    main()
